#implicit
number=10
character='a'
floating_point=10.25
boolean=True
print(type(number))
print(type(character))
print(type(floating_point))
print(type(boolean))

#explicit
num=int(10)
char=str('a')
decimal=float(10.25)
b=bool(False)
print(type(num))
print(type(char))
print(type(decimal))
print(type(b))


